import math


def printSudoku(board):
    N = len(board)
    n = int(math.sqrt(N))

    for i in range(N):
        if i % n == 0 and i != 0:
            print("----------------------")
        row = ""
        for j in range(N):
            if j % n == 0 and j != 0:
                row += "| "
            val = board[i][j]
            row += (str(val) if val != 0 else ".") + " "
        print(row)
    print()


